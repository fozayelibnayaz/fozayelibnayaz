def main() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    written = []
    for name, spec in SKILL_SETS.items():
        svg = build(spec["title"], spec["subtitle"], spec["accent"], spec["rows"])
        path = os.path.join(OUT_DIR, name)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(svg)
        written.append((name, len(svg)))

    # NOTE: assets/now.svg is owned by auto_update.py, not by this script.
    # build_now_card() lives here only so auto_update.py can import it.

    for name, size in written:
        print(f"  wrote {name:26} {size:>7} bytes")
    print(f"\n{len(written)} SVG assets generated in {OUT_DIR}")


if __name__ == "__main__":
    main()
