"""
gen_skills_svg.py -- builds the animated skill-bar SVGs used in the profile README.

Everything is self-contained (no external fonts, no CSS <style> blocks) because
GitHub sanitizes <style>/<script> out of markdown. Animation uses SMIL <animate>,
which DOES run on GitHub's raw-content renderer.

Usage:  python3 bin/gen_skills_svg.py
Output: github-profile/fozayelibnayaz/assets/skills-*.svg
        (assets/now.svg is generated by auto_update.py -- see the note in main())
"""
from __future__ import annotations

